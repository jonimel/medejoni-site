/** English alt text from a photo's file name, e.g. 'jardin-cave-waterfall' → 'Jardin cave waterfall'. */
export const altEn = (slug: string) => {
  const s = slug.replace(/-/g, ' ');
  return s.charAt(0).toUpperCase() + s.slice(1);
};
